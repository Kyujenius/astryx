import fs from 'node:fs';
import path from 'node:path';
import {inspect} from 'node:util';
import {fileURLToPath} from 'node:url';
import {buildButtonFamilyAccessibilityThemeCoverage} from './accessibility/button-family-audit-profiles.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(
  ROOT,
  'packages/core/src/Button/buttonFamilyAccessibilityThemeCoverage.mjs',
);
const EXPORTS = {
  Button: 'buttonAccessibilityThemeCoverage',
  IconButton: 'iconButtonAccessibilityThemeCoverage',
  ToggleButton: 'toggleButtonAccessibilityThemeCoverage',
  ButtonGroup: 'buttonGroupAccessibilityThemeCoverage',
  SegmentedControl: 'segmentedControlAccessibilityThemeCoverage',
};

function generatedSource() {
  const coverage = buildButtonFamilyAccessibilityThemeCoverage();
  const exports = Object.entries(EXPORTS)
    .map(
      ([component, exportName]) =>
        `export const ${exportName} = ${inspect(coverage[component], {
          breakLength: 100,
          compact: true,
          depth: null,
        })};`,
    )
    .join('\n\n');
  return `// Copyright (c) Meta Platforms, Inc. and affiliates.\n\n// Generated by scripts/generate-button-family-accessibility-coverage.mjs.\n\n${exports}\n`;
}

const next = generatedSource();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== next) {
    console.error(
      'Button-family accessibility coverage is stale. Run: pnpm exec tsx scripts/generate-button-family-accessibility-coverage.mjs',
    );
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(OUTPUT, next);
  console.log(`Generated ${path.relative(ROOT, OUTPUT)}`);
}
